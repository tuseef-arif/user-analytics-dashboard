from collections.abc import Iterator
from pathlib import Path

import pytest
import sqlalchemy as sa
from alembic import command
from sqlalchemy import Engine, inspect
from sqlmodel import Session, create_engine, func, select

from api.models import Gender, User
from tests.alembic_helpers import run_alembic, upgrade_head


@pytest.fixture
def bare_engine(tmp_path: Path) -> Iterator[Engine]:
    # Unlike the conftest engine, no tables exist until a migration creates them.
    engine = create_engine(f"sqlite:///{tmp_path / 'migrate.db'}")
    yield engine
    engine.dispose()


def _user_count(engine: Engine) -> int:
    with Session(engine) as session:
        return session.exec(select(func.count()).select_from(User)).one()


def test_upgrade_creates_users_table(bare_engine: Engine) -> None:
    upgrade_head(bare_engine)
    tables = inspect(bare_engine).get_table_names()
    assert "users" in tables
    assert "user" not in tables


def test_models_match_migrations(bare_engine: Engine) -> None:
    upgrade_head(bare_engine)
    # Fails with AutoGenerateDiffsDetected if a model changes without a migration.
    run_alembic(bare_engine, command.check)


def test_upgrade_twice_keeps_rows(bare_engine: Engine) -> None:
    upgrade_head(bare_engine)
    with Session(bare_engine) as session:
        session.add(User(username="keepme", password_hash="h", gender=Gender.other))
        session.commit()

    upgrade_head(bare_engine)
    assert _user_count(bare_engine) == 1


def test_upgrade_renames_legacy_user_table(bare_engine: Engine) -> None:
    # Recreate the pre-Alembic schema that create_all produced as table "user".
    legacy = sa.MetaData()
    sa.Table(
        "user",
        legacy,
        sa.Column("id", sa.Integer, primary_key=True),
        sa.Column("username", sa.String(64), nullable=False),
        sa.Column("password_hash", sa.String, nullable=False),
        sa.Column(
            "gender",
            sa.Enum("male", "female", "other", name="gender"),
            nullable=False,
        ),
        sa.Column("created_at", sa.DateTime(timezone=True), nullable=False),
        sa.Index("ix_user_username", "username", unique=True),
    )
    legacy.create_all(bare_engine)
    with bare_engine.begin() as connection:
        connection.execute(
            sa.text(
                'INSERT INTO "user" (username, password_hash, gender, created_at) '
                "VALUES ('legacy', 'h', 'male', '2026-01-01 00:00:00')"
            )
        )

    upgrade_head(bare_engine)

    inspector = inspect(bare_engine)
    assert "user" not in inspector.get_table_names()
    assert [ix["name"] for ix in inspector.get_indexes("users")] == ["ix_users_username"]
    with Session(bare_engine) as session:
        assert session.exec(select(User.username)).all() == ["legacy"]
    run_alembic(bare_engine, command.check)


def test_downgrade_then_upgrade(bare_engine: Engine) -> None:
    upgrade_head(bare_engine)
    run_alembic(bare_engine, command.downgrade, "base")
    assert "users" not in inspect(bare_engine).get_table_names()
    upgrade_head(bare_engine)
    assert "users" in inspect(bare_engine).get_table_names()
